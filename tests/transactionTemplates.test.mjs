import assert from 'node:assert/strict';
import {normalizeTemplates,templatePayload,applyTransactionTemplate} from '../src/transactionTemplates.js';
const accounts=[{id:'a',type:'cash'},{id:'b',type:'bank'},{id:'trust',type:'trust'}];
const categories={expense:{餐飲美食:['午餐','晚餐']},income:{主動收入:['薪資所得']}};
const projects=[{id:'p',name:'旅行'}];
const base={date:'2026-11-05',type:'expense',amount:'',account:'a',fromAccount:'a',toAccount:'b',mainCategory:'餐飲美食',subCategory:'午餐',note:'',projectId:''};
const stored=templatePayload({...base,date:'2001-01-01',id:'transaction',recurringId:'recurring'});
assert.equal(stored.date,undefined);
assert.equal(stored.id,undefined);
assert.equal(stored.recurringId,undefined);
assert.equal(stored.type,'expense');
let result=applyTransactionTemplate(base,{...stored,amount:'125',note:'午餐'},accounts,categories,projects);
assert.equal(result.date,'2026-11-05');
assert.equal(result.amount,'125');
assert.equal(result.note,'午餐');
result=applyTransactionTemplate(base,{...stored,account:'deleted',mainCategory:'deleted',subCategory:'deleted',projectId:'deleted'},accounts,categories,projects);
assert.equal(result.account,'a');
assert.equal(result.mainCategory,'餐飲美食');
assert.equal(result.subCategory,'午餐');
assert.equal(result.projectId,'');
result=applyTransactionTemplate(base,{...stored,type:'transfer',fromAccount:'a',toAccount:'a'},accounts,categories,projects);
assert.equal(result.toAccount,'b');
assert.equal(result.mainCategory,'帳戶互轉');
assert.equal(result.date,'2026-11-05');
const normalized=normalizeTemplates([{id:'x',name:'午餐',...stored},{id:'x',name:'duplicate'},{id:'y',name:'交通',type:'expense'}]);
assert.equal(normalized.length,2);
assert.equal(normalized[1].amount,'');
console.log('Transaction template tests passed');
