import assert from 'node:assert/strict';
import {defaultCategories,migrateCategoryData,v168Categories} from '../src/categoryPresets.js';
const expense=Object.keys(defaultCategories.expense);
assert.equal(expense.length,14);
assert.equal(Object.keys(defaultCategories.income).length,4);
assert.equal(expense[expense.indexOf('電信')+1],'訂閱服務');
assert(defaultCategories.expense['訂閱服務'].includes('雲端伺服器'));
assert(defaultCategories.expense['休閒娛樂'].includes('樂透'));
for(const name of ['健康檢查','醫療處置','復健治療']) assert(!defaultCategories.expense['醫療＆健康'].includes(name));
assert.deepEqual(defaultCategories.expense['送禮＆捐贈'],['送禮','婚喪喜慶','公益捐款','其他送禮']);
const records=[{id:'r1',type:'expense',mainCategory:'飲食',subCategory:'飲料咖啡'},{id:'r2',type:'expense',mainCategory:'電信',subCategory:'訂閱服務'},{id:'r3',type:'transfer',mainCategory:'帳戶互轉',subCategory:'內部轉帳'}];
const recurring=[{id:'rr1',type:'income',mainCategory:'意外收入',subCategory:'退款退費'}];
const migrated=migrateCategoryData(v168Categories,records,recurring,{'expense/main/飲食':'utensils'});
assert.deepEqual([migrated.records[0].mainCategory,migrated.records[0].subCategory],['餐飲美食','飲料']);
assert.deepEqual([migrated.records[1].mainCategory,migrated.records[1].subCategory],['訂閱服務','其他訂閱']);
assert.equal(migrated.records[2].mainCategory,'帳戶互轉');
assert.deepEqual([migrated.recurring[0].mainCategory,migrated.recurring[0].subCategory],['其他收入','退款退費']);
assert.equal(migrated.icons['expense/main/餐飲美食'],'utensils');
assert.equal(Object.keys(migrated.categories.expense).length,14);
const customized=migrateCategoryData({...v168Categories,expense:{...v168Categories.expense,'私人用途':['自訂子分類']}},[{id:'r4',type:'expense',mainCategory:'私人用途',subCategory:'自訂子分類'}]);
assert(customized.categories.expense['私人用途'].includes('自訂子分類'));
assert.equal(customized.records[0].mainCategory,'私人用途');
console.log('NEXPEN category preset and migration tests passed');
